<details>
	<summary class="link">Comment fonctionne l'inscription ?</summary>
	<dl class="meta">
		<dt>Loterie</dt>
		<dd>L'inscription ouvre 1 h 30 avant l'activité (au plus tôt 9 h 30). Jusqu'au tirage, 45 min avant, l'heure à laquelle vous vous inscrivez ne compte pas. Une loterie perdue libère tout de suite votre billet.</dd>
		<dt>Premier arrivé</dt>
		<dd>Après le tirage, les places restantes partent dans l'ordre des inscriptions.</dd>
		<dt>File d'attente</dt>
		<dd>Une fois complet, un quart des places est ouvert en file. Être en file n'est pas une place garantie : le prestataire fait entrer la file dans l'ordre d'arrivée s'il reste de la place.</dd>
		<dt>Groupe</dt>
		<dd>Jusqu'à 6 billets, tous ou personne : si le tirage ne peut pas placer tout le groupe, personne n'est pris. Un billet trop jeune bloque : le groupe s'inscrit sans lui ou renonce.</dd>
		<dt>Un billet, une activité</dt>
		<dd>Une seule inscription active par billet, sans chevauchement. Le billet se libère à la moitié de l'activité en cours.</dd>
	</dl>
</details>

